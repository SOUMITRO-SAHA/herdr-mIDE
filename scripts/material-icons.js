// Parses Material Icon Theme's file associations into mods/mide-files/icons.js.
// Run via scripts/update-icons.sh — not standalone.
// Reads:  <fileIcons.ts>  Material Icon Theme's src/core/icons/fileIcons.ts (MIT)
//         <icons dir>     the theme's built SVGs from the npm package
// Writes: <map out>       icons.js: SUFFIX (extension match, longest dotted
//                         suffix first: foo.d.ts tries "d.ts" then "ts"),
//                         NAMES (whole file name), PREFIX (empty — Material
//                         has no prefix associations)
const [srcFile, iconsDir, mapOut, version] = process.argv.slice(2);
const fs = require("fs");
const path = require("path");

// — The keep list: a minimal IDE carries only what coding projects actually
// use. Languages are the practical top 20 cross-referenced from TIOBE
// (Nov 2025), the Stack Overflow 2025 survey and PYPL; everything else
// falls back to the plain `file` glyph. Folder glyphs live separately in
// icons/ (folder.svg, folder-open.svg) — this set is file icons only.
const KEEP_ICONS = new Set([
  // languages (top 20) + their immediate family files
  "python",            // .py, pyproject-adjacent
  "javascript",        // .js, .mjs, .cjs
  "typescript",        // .ts, .mts, .cts
  "typescript-def",    // .d.ts
  "java",              // .java
  "csharp",            // .cs
  "cpp",               // .cpp, .cc, .cxx, .hpp, .hh…
  "c",                 // .c
  "h",                 // .h (C/C++ headers have their own glyph)
  "php",               // .php
  "go",                // .go
  "go-mod",            // go.mod / go.sum
  "rust",              // .rs
  "ruby",              // .rb, Gemfile
  "kotlin",            // .kt, .kts
  "swift",             // .swift
  "dart",              // .dart
  "lua",               // .lua
  "scala",             // .scala, .sc
  "r",                 // .r, .R
  "database",          // .sql
  "console",           // .sh, .bash, .zsh, .fish
  // the practical face of JS/TS: React and Vue files
  "react",             // .jsx
  "react_ts",          // .tsx
  "vue",               // .vue
  // universal non-language files
  "file",              // the unknown-type fallback
  "git",               // .gitignore, .gitattributes…
  "lock",              // *.lock
  "yaml",              // .yaml, .yml
  "toml",              // .toml
  "json",              // .json
  "markdown",          // .md
  "readme",            // README
  "html",              // .html
  "css",               // .css
  "sass",              // .scss, .sass
  "docker",            // Dockerfile, compose files
  "license",           // LICENSE
  "makefile",          // Makefile
  "image",             // .png, .jpg, .svg, .ico…
  "nodejs",            // package.json
  "tsconfig",          // tsconfig.json
  "editorconfig",      // .editorconfig
  "settings",          // .ini, .conf
  "tune",              // .env
  "maven",             // pom.xml
  "gradle",            // build.gradle(.kts)
]);

const keep = (icon) => KEEP_ICONS.has(icon);

const src = fs.readFileSync(srcFile, "utf8");
const SUFFIX = {}, NAMES = {};

// Each icon object is flat (string arrays only), so the first `}` after a
// `name:` closes it. filenamePatterns entries are skipped: they are regex
// associations this resolver does not model. Entries gated behind optional
// icon packs (`enabledFor:`) are skipped too — upstream keeps them off by
// default, and they would overwrite the default associations.
for (const [, name, body] of src.matchAll(/name:\s*['"]([^'"]+)['"]([^{}]*)\}/g)) {
  if (/enabledFor:|disabled:\s*true/.test(body)) continue;
  for (const [key, table] of [["fileExtensions", SUFFIX], ["fileNames", NAMES]]) {
    const m = body.match(new RegExp(key + ":\\s*\\[([^\\]]*)\\]"));
    if (!m) continue;
    for (const v of m[1].matchAll(/['"]([^'"]+)['"]/g)) {
      table[v[1].toLowerCase()] = name;
    }
  }
}

// Associations: keep only icons in the minimal set — everything else
// resolves to the generic file glyph at render time.
const suffix = {}, names = {};
for (const [key, table, out] of [["fileExtensions", SUFFIX, suffix], ["fileNames", NAMES, names]]) {
  for (const [k, icon] of Object.entries(table)) if (keep(icon)) out[k] = icon;
}

// Sanity: every kept icon must exist on disk.
const missing = [...new Set([...Object.values(suffix), ...Object.values(names)])]
  .filter((icon) => !fs.existsSync(path.join(iconsDir, `${icon}.svg`)));
if (missing.length) {
  console.error(`  ! keep-list icons missing on disk: ${missing.join(", ")}`);
  process.exit(1);
}

const line = (obj) => JSON.stringify(obj).replace(/",/g, '",\n  ').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}");
fs.writeFileSync(mapOut,
`// Generated by scripts/update-icons.sh — do not edit by hand.
// Source: Material Icon Theme (MIT, © Material Extensions), v${version}
// — https://github.com/material-extensions/vscode-material-icon-theme.
// Resolution order in mide-files: NAMES (exact file name) → SUFFIX
// (longest dotted suffix first: foo.d.ts tries "d.ts" then "ts") →
// PREFIX (empty: Material has no prefix associations).
export const SUFFIX = ${line(suffix)};
export const NAMES = ${line(names)};
export const PREFIX = [];
`);

// Prune SVGs outside the keep list (folder variants, clones, niche
// languages, tooling logos): the mod ships only what it renders.
let removed = 0;
for (const f of fs.readdirSync(iconsDir)) {
  if (f.endsWith(".svg") && !KEEP_ICONS.has(f.replace(/\.svg$/, ""))) {
    fs.unlinkSync(path.join(iconsDir, f));
    removed++;
  }
}
if (removed) console.log(`  pruned ${removed} icons outside the keep list`);

console.log(`  associations: ${Object.keys(suffix).length} suffix, ${Object.keys(names).length} name`);
